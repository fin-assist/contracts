#!/usr/bin/env python3
"""Check the gRPC error registry (finassist.common.v1.ErrorReason) against its rules.

Usage:
    buf build -o fd.binpb
    python3 scripts/check_error_registry.py fd.binpb path/to/api.md

Checks:
  1. Every ErrorReason value except UNSPECIFIED has a complete (error_spec):
     grpc_code set, http_status in 400..599, snake_case unique metadata keys.
  2. (error_spec) is used only on ErrorReason: no per-service error registries.
  3. The registry has at most MAX_REASONS codes. Raising the cap is a reviewed
     change of this file (CODEOWNERS).
  4. The registry matches the error table in api.md, section 8: same codes and
     the same HTTP status. Stream-only codes (HTTP "—") and codes that only
     bank-bff returns (BFF_ONLY) are excluded.

Exit code 0 when everything passes, 1 otherwise.
"""

import re
import sys

from google.protobuf import descriptor_pb2, descriptor_pool, message_factory

REGISTRY = "finassist.common.v1.ErrorReason"
SPEC_EXT = "finassist.common.v1.error_spec"
MAX_REASONS = 30
# Codes generated by bank-bff itself (FIN-20); they are in api.md but not in the registry.
BFF_ONLY = {"MAINTENANCE", "CLIENT_VERSION_UNSUPPORTED"}
SNAKE = re.compile(r"^[a-z][a-z0-9]*(_[a-z0-9]+)*$")
TABLE_ROW = re.compile(r"^\|\s*`([A-Z][A-Z0-9_]*)`\s*\|\s*([^|]+?)\s*\|")


def load_pool(path):
    fds = descriptor_pb2.FileDescriptorSet()
    with open(path, "rb") as f:
        fds.ParseFromString(f.read())
    pool = descriptor_pool.DescriptorPool()
    for fd in fds.file:
        pool.Add(fd)
    # Build classes for every file so the custom option extension gets registered.
    message_factory.GetMessageClassesForFiles([fd.name for fd in fds.file], pool)
    return fds, pool


def options_with_ext(pool, raw_options):
    """Re-parse EnumValueOptions with the pool's class, which knows our extension."""
    cls = message_factory.GetMessageClass(
        pool.FindMessageTypeByName("google.protobuf.EnumValueOptions"))
    opts = cls()
    opts.ParseFromString(raw_options.SerializeToString())
    return opts


def api_md_codes(path):
    """Error table of api.md section 8 -> {code: http_status or None for stream-only}."""
    with open(path, encoding="utf-8") as f:
        text = f.read()
    m = re.search(r"^## 8\..*?$(.*?)^## ", text, re.M | re.S)
    if not m:
        raise SystemExit(f"{path}: section 8 (error registry) not found")
    codes = {}
    for line in m.group(1).splitlines():
        row = TABLE_ROW.match(line)
        if row:
            http = row.group(2)
            codes[row.group(1)] = int(http) if http.isdigit() else None
    return codes


def main(fd_path, api_md_path):
    fds, pool = load_pool(fd_path)
    ext = pool.FindExtensionByName(SPEC_EXT)
    errors = []

    registry = {}
    for fd in fds.file:
        file_desc = pool.FindFileByName(fd.name)
        enums = list(file_desc.enum_types_by_name.values())
        stack = list(file_desc.message_types_by_name.values())
        while stack:
            msg = stack.pop()
            enums.extend(msg.enum_types)
            stack.extend(msg.nested_types)
        for enum in enums:
            for value in enum.values:
                if not value.GetOptions().ByteSize():
                    continue
                opts = options_with_ext(pool, value.GetOptions())
                has_spec = opts.HasExtension(ext)
                if enum.full_name != REGISTRY:
                    if has_spec:
                        errors.append(
                            f"{enum.full_name}.{value.name}: error_spec outside {REGISTRY}; "
                            "services must not keep their own error registries")
                    continue
                registry[value.name] = opts.Extensions[ext] if has_spec else None

    registry_enum = pool.FindEnumTypeByName(REGISTRY)
    for value in registry_enum.values:
        if value.number == 0:
            continue
        spec = registry.get(value.name)
        where = f"{REGISTRY}.{value.name}"
        if spec is None:
            errors.append(f"{where}: missing (error_spec)")
            continue
        if spec.grpc_code == 0:
            errors.append(f"{where}: grpc_code is not set")
        if not 400 <= spec.http_status <= 599:
            errors.append(f"{where}: http_status {spec.http_status} is not 4xx/5xx")
        keys = list(spec.metadata_keys)
        if len(keys) != len(set(keys)):
            errors.append(f"{where}: duplicate metadata_keys")
        for key in keys:
            if not SNAKE.match(key):
                errors.append(f"{where}: metadata key {key!r} is not snake_case")
        registry[value.name] = spec

    reasons = {v.name: registry[v.name] for v in registry_enum.values if v.number != 0}
    if len(reasons) > MAX_REASONS:
        errors.append(
            f"{REGISTRY}: {len(reasons)} codes, limit is {MAX_REASONS}. Reuse an existing code "
            "with metadata/BadRequest, or raise the limit in a reviewed change")

    documented = api_md_codes(api_md_path)
    for name, spec in reasons.items():
        if name not in documented:
            errors.append(f"{name}: in the registry but not in api.md section 8")
        elif documented[name] is None:
            errors.append(f"{name}: api.md lists it as a stream-only code, but it is a gRPC error")
        elif spec is not None and documented[name] != spec.http_status:
            errors.append(
                f"{name}: http_status {spec.http_status} in proto, {documented[name]} in api.md")
    for name, http in documented.items():
        if http is not None and name not in reasons and name not in BFF_ONLY:
            errors.append(f"{name}: in api.md section 8 but not in the registry")

    if errors:
        print("error registry check failed:")
        for e in errors:
            print(f"  - {e}")
        return 1
    print(f"error registry OK: {len(reasons)}/{MAX_REASONS} codes, in sync with api.md")
    return 0


if __name__ == "__main__":
    if len(sys.argv) != 3:
        raise SystemExit(__doc__)
    sys.exit(main(sys.argv[1], sys.argv[2]))
